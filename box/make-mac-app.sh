#!/usr/bin/env bash
# Build ~/Applications/Ghostbox.app: one click starts Docker and the box if needed, then opens
# the live view in its own window. Usage: box/make-mac-app.sh [--dock]
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
APP="$HOME/Applications/Ghostbox.app"
TMP="$(mktemp -d)"

mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cat > "$APP/Contents/Info.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>CFBundleName</key><string>Ghostbox</string>
  <key>CFBundleIdentifier</key><string>dev.ghosthands.ghostbox</string>
  <key>CFBundleExecutable</key><string>ghostbox-launch</string>
  <key>CFBundleIconFile</key><string>Ghostbox</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleVersion</key><string>1</string>
  <key>LSUIElement</key><true/>
</dict></plist>
EOF

cat > "$APP/Contents/MacOS/ghostbox-launch" <<EOF
#!/bin/bash
# Generated by box/make-mac-app.sh
export PATH="/usr/local/bin:/opt/homebrew/bin:/Applications/Docker.app/Contents/Resources/bin:\$PATH"
GB="$HERE/ghostbox"
LOG="\$HOME/Library/Logs/ghostbox-launch.log"
note() { osascript -e "display notification \"\$1\" with title \"Ghostbox\"" >/dev/null 2>&1 || true; }
{
  if ! docker info >/dev/null 2>&1; then
    note "Starting Docker…"; open -g -a Docker
    for _ in \$(seq 90); do docker info >/dev/null 2>&1 && break; sleep 2; done
  fi
  if [ "\$(docker inspect -f '{{.State.Running}}' ghostbox 2>/dev/null)" != true ]; then
    note "Starting the box…"
    docker start ghostbox >/dev/null 2>&1 || "\$GB" up 2>&1 | sed -E 's/password=[^&[:space:]]*/password=REDACTED/g'
    for _ in \$(seq 60); do "\$GB" watch 2>/dev/null | grep -q 'password=.' && break; sleep 1; done
  fi
  URL="\$("\$GB" watch | sed 's/^watch: //')"
  open -na "Google Chrome" --args --app="\$URL" --window-size=1460,960
} 2>&1 | sed -E 's/password=[^&[:space:]]*/password=REDACTED/g' >>"\$LOG"
EOF
chmod +x "$APP/Contents/MacOS/ghostbox-launch"

# Icon: a ghost on a dark rounded square, drawn with AppKit.
cat > "$TMP/icon.swift" <<'EOF'
import AppKit
let size = 1024.0
let img = NSImage(size: NSSize(width: size, height: size))
img.lockFocus()
NSColor(calibratedRed: 0.11, green: 0.12, blue: 0.16, alpha: 1).setFill()
NSBezierPath(roundedRect: NSRect(x: 100, y: 100, width: 824, height: 824), xRadius: 185, yRadius: 185).fill()
let s = "👻" as NSString
let attrs: [NSAttributedString.Key: Any] = [.font: NSFont.systemFont(ofSize: 560)]
let b = s.size(withAttributes: attrs)
s.draw(at: NSPoint(x: (size - b.width) / 2, y: (size - b.height) / 2 - 10), withAttributes: attrs)
img.unlockFocus()
let rep = NSBitmapImageRep(data: img.tiffRepresentation!)!
try! rep.representation(using: .png, properties: [:])!.write(to: URL(fileURLWithPath: CommandLine.arguments[1]))
EOF
swift "$TMP/icon.swift" "$TMP/icon.png"
mkdir -p "$TMP/Ghostbox.iconset"
for s in 16 32 128 256 512; do
  sips -z $s $s "$TMP/icon.png" --out "$TMP/Ghostbox.iconset/icon_${s}x${s}.png" >/dev/null
  sips -z $((s*2)) $((s*2)) "$TMP/icon.png" --out "$TMP/Ghostbox.iconset/icon_${s}x${s}@2x.png" >/dev/null
done
iconutil -c icns "$TMP/Ghostbox.iconset" -o "$APP/Contents/Resources/Ghostbox.icns"
touch "$APP"
echo "built $APP"

if [ "${1:-}" = "--dock" ] && ! defaults read com.apple.dock persistent-apps | grep -q "Ghostbox.app"; then
  defaults write com.apple.dock persistent-apps -array-add \
    "<dict><key>tile-data</key><dict><key>file-data</key><dict><key>_CFURLString</key><string>file://$APP/</string><key>_CFURLStringType</key><integer>15</integer></dict></dict></dict>"
  killall Dock
  echo "added to the Dock"
fi
